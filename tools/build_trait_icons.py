"""Build the approved PNG masters into CK3's existing 120px trait DDS format.

Requires Pillow. --check compares generated bytes without changing any files.
"""
import argparse
from pathlib import Path
import re
import struct

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SIZE = 120


def dds_bytes(source: Path) -> bytes:
    with Image.open(source) as image:
        rgba = image.convert('RGBA')
        if rgba.getchannel('A').getextrema() != (0, 255):
            raise ValueError(f'Expected transparent RGBA artwork: {source.name}')
        native = rgba.resize((SIZE, SIZE), Image.Resampling.LANCZOS)
    # DDS_HEADER + DDS_PIXELFORMAT: pitch, RGBA masks, texture caps; no mipmaps.
    header = struct.pack('<4s31I', b'DDS ',
                         124, 0x100F, SIZE, SIZE, SIZE * 4, 0, 0,
                         *([0] * 11),
                         32, 0x41, 0, 32,
                         0x00FF0000, 0x0000FF00, 0x000000FF, 0xFF000000,
                         0x1000, 0, 0, 0, 0)
    return header + native.tobytes('raw', 'BGRA')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    definitions = (ROOT / 'AuraClash/common/traits/ac_cultivation_traits.txt').read_text(encoding='utf-8-sig')
    traits = set(re.findall(r'^(ac_\w+)\s*=\s*\{', definitions, re.M))
    source_dir = ROOT / 'assets/trait-icons/source'
    sources = {path.stem: path for path in source_dir.glob('*.png')}
    if traits != set(sources):
        raise SystemExit(f'Trait/artwork mismatch: missing={sorted(traits - set(sources))}, extra={sorted(set(sources) - traits)}')
    for trait in sorted(traits):
        data = dds_bytes(sources[trait])
        target = ROOT / 'AuraClash/gfx/interface/icons/traits' / (trait + '.dds')
        if args.check:
            if not target.is_file() or target.read_bytes() != data:
                raise SystemExit(f'Stale trait icon: {target.relative_to(ROOT)}')
        else:
            target.write_bytes(data)
    print(('Verified' if args.check else 'Built') + f' {len(traits)} trait icons.')


if __name__ == '__main__':
    main()
